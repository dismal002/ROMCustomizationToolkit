base_dir = '/home/dismal/Downloads/ROM Customization Toolkit-Qt/translations'

for lang, trans_map in translations.items():
    filepath = os.path.join(base_dir, f'ct_{lang}.ts')
    if not os.path.exists(filepath):
        print(f"File {filepath} does not exist!")
        continue
    tree = ET.parse(filepath)
    root = tree.getroot()
    count = 0
    for message in root.findall('.//message'):
        source = message.find('source')
        translation = message.find('translation')
        if source is not None and source.text:
            src_text = source.text.strip()
            if src_text in trans_map:
                translation.text = trans_map[src_text]
                if 'type' in translation.attrib:
                    del translation.attrib['type']
                count += 1
    tree.write(filepath, encoding='utf-8', xml_declaration=True)
    print(f"Updated {filepath}: {count} strings translated.")
